export function getAuthorBySlug(slug: string) {
  return authors.find((a) => a.slug === slug);
}

export function getAuthorByName(name: string) {
  const n = name.toLowerCase().trim();
  return (
    authors.find((a) => a.name.toLowerCase() === n) ||
    authors.find((a) => a.name.toLowerCase().includes(n) || n.includes(a.name.toLowerCase())) ||
    authors.find((a) => a.slug.replace(/-/g, " ") === n)
  );
}

/** AI-style similar author recommendation by liked author name */
export function recommendAuthorsLike(nameOrSlug: string, limit = 5) {
  const hit = getAuthorByName(nameOrSlug) || getAuthorBySlug(nameOrSlug);
  if (!hit) return authors.slice(0, limit);
  const bySimilar = hit.similarAuthors
    .map((s) => authors.find((a) => a.slug === s))
    .filter(Boolean) as typeof authors;
  if (bySimilar.length >= limit) return bySimilar.slice(0, limit);
  const extra = authors.filter(
    (a) =>
      a.slug !== hit.slug &&
      !bySimilar.some((s) => s.slug === a.slug) &&
      a.categories.some((c) => hit.categories.includes(c))
  );
  return [...bySimilar, ...extra].slice(0, limit);
}

