import type { Book } from "@/types";
import { coverForBook } from "@/data/covers";

const now = "2026-07-01T00:00:00.000Z";

function book(
  partial: Partial<Book> &
    Pick<
      Book,
      | "id"
      | "title"
      | "slug"
      | "isbn"
      | "author"
      | "publisher"
      | "category"
      | "subCategory"
      | "publishYear"
      | "pages"
      | "description"
      | "summary"
      | "price"
      | "salePrice"
      | "stock"
      | "sold"
      | "rating"
      | "reviewCount"
      | "coverGradient"
      | "ebook"
      | "audiobook"
      | "featured"
      | "bestseller"
      | "newArrival"
      | "flashSale"
      | "tags"
    >
): Book {
  const discount =
    partial.discount ??
    (partial.price && partial.salePrice
      ? Math.round(((partial.price - partial.salePrice) / partial.price) * 100)
      : 0);
  return {
    translator: "",
    language: "Tiếng Việt",
    edition: "1",
    size: "14.5 x 20.5 cm",
    weight: "350g",
    coverType: "Bìa mềm",
    tableOfContents: ["Lời mở đầu", "Chương 1", "Chương 2", "Kết luận"],
    previewPages: [],
    relatedBooks: [],
    currency: "VND",
    createdAt: now,
    updatedAt: now,
    ...partial,
    discount,
    images: partial.images?.length
      ? partial.images
      : [coverForBook(partial.id)],
  };
}

